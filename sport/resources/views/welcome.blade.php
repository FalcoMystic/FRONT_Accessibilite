            <h1>La musculation, une pratique complète pour renforcer son corps</h1>

            <section id="presentation" aria-labelledby="titre-presentation">
                <h2 id="titre-presentation">Présentation de la musculation</h2>
                <p>
                    La musculation consiste à exercer les muscles contre une résistance, avec le poids du corps,
                    des haltères, des barres, des machines ou des élastiques. Les mouvements sont répétés de façon
                    contrôlée afin de développer la force, l'endurance musculaire et la maîtrise du geste.
                </p>
                <p>
                    Pratiquée régulièrement et avec une technique adaptée, elle contribue à renforcer les muscles,
                    les os et les articulations. Elle peut également améliorer la posture, l'équilibre et la capacité
                    à accomplir les gestes du quotidien. Associée à une alimentation variée, à un sommeil suffisant
                    et à une activité cardiovasculaire, elle participe à une meilleure santé globale.
                </p>
                <p>
                    Les bénéfices dépendent de la régularité, de la progression et de l'adaptation de l'effort aux
                    capacités de chaque personne. En cas de douleur persistante, de problème de santé ou de reprise
                    après une longue interruption, demandez conseil à un professionnel de santé.
                </p>
            </section>

            <section id="organisation" aria-labelledby="titre-organisation">
                <h2 id="titre-organisation">Comment bien débuter et s'organiser</h2>
                <p>
                    Pour commencer en salle, choisissez des charges qui permettent de conserver une posture stable et
                    d'effectuer chaque mouvement avec amplitude et contrôle. Une séance peut comprendre un échauffement
                    progressif, les exercices de renforcement, puis un retour au calme. Apprenez les réglages des
                    machines et demandez une démonstration à un encadrant lorsque vous ne maîtrisez pas un mouvement.
                </p>

                <h3>Un programme Full-body trois jours par semaine</h3>
                <p>
                    Le programme Full-body sollicite les principaux groupes musculaires au cours de chaque séance.
                    Trois entraînements hebdomadaires, séparés par au moins un jour de récupération, offrent un cadre
                    simple et régulier. Par exemple, les séances peuvent avoir lieu le lundi, le mercredi et le vendredi.
                </p>
                <ol>
                    <li>
                        <strong>Jour 1 :</strong> travail technique à intensité modérée avec un mouvement de jambes,
                        une poussée, une traction et un exercice de gainage.
                    </li>
                    <li>
                        <strong>Jour 2 :</strong> reprise des mêmes grandes familles de mouvements avec des variantes
                        adaptées, en privilégiant la qualité d'exécution.
                    </li>
                    <li>
                        <strong>Jour 3 :</strong> séance complète et progressive, sans chercher l'échec musculaire,
                        suivie d'un repos suffisant avant la semaine suivante.
                    </li>
                </ol>

                <h3>Les repères d'une séance équilibrée</h3>
                <ul>
                    <li>Commencer par cinq à dix minutes de mobilisation et d'échauffement progressif.</li>
                    <li>Réaliser deux à quatre séries par exercice selon le niveau et le volume prévu.</li>
                    <li>Garder une à trois répétitions possibles en réserve pour apprendre à progresser sans précipitation.</li>
                    <li>Prendre le temps de récupérer entre les séries et boire régulièrement.</li>
                    <li>Noter les charges, les répétitions et les sensations pour suivre les progrès.</li>
                    <li>Prévoir des jours sans musculation pour permettre la récupération des muscles et du système nerveux.</li>
                </ul>
            </section>

            <section id="exercices" aria-labelledby="titre-exercices">
                <h2 id="titre-exercices">Les exercices fondamentaux</h2>
                <p>
                    Ces exercices couvrent les principaux mouvements utiles dans une routine Full-body. Commencez par
                    une variante que vous pouvez réaliser sans douleur et faites-vous corriger si nécessaire.
                </p>

                <article>
                    <h3>Squat</h3>
                    <p>
                        Le squat consiste à fléchir les hanches et les genoux en gardant le buste maîtrisé, puis à
                        repousser le sol pour revenir debout.
                    </p>
                    <p><strong>Muscles ciblés :</strong> quadriceps, fessiers et ischio-jambiers, avec une participation importante du gainage.</p>
                </article>

                <article>
                    <h3>Soulevé de terre</h3>
                    <p>
                        Le soulevé de terre commence avec une charge proche des jambes. On pousse dans le sol et on
                        redresse les hanches en conservant le dos dans une position stable, puis on repose la charge
                        avec contrôle.
                    </p>
                    <p><strong>Muscles ciblés :</strong> fessiers, ischio-jambiers, muscles du dos et avant-bras.</p>
                </article>

                <article>
                    <h3>Développé couché</h3>
                    <p>
                        Allongé sur un banc, on descend la barre ou les haltères vers la poitrine, puis on pousse les
                        charges vers le haut sans perdre la stabilité des épaules.
                    </p>
                    <p><strong>Muscles ciblés :</strong> pectoraux, triceps et partie antérieure des épaules.</p>
                </article>

                <article>
                    <h3>Traction ou tirage vertical</h3>
                    <p>
                        Le mouvement consiste à tirer le corps vers une barre, ou une poignée vers le haut de la
                        poitrine sur une machine, en abaissant les épaules et en contrôlant la remontée.
                    </p>
                    <p><strong>Muscles ciblés :</strong> grand dorsal, muscles du haut du dos et biceps.</p>
                </article>

                <article>
                    <h3>Développé au-dessus de la tête</h3>
                    <p>
                        Depuis une position stable, on pousse les haltères ou la barre au-dessus de la tête, puis on
                        redescend lentement sans cambrer excessivement le dos.
                    </p>
                    <p><strong>Muscles ciblés :</strong> épaules et triceps ; les muscles du tronc stabilisent le mouvement.</p>
                </article>

                <article>
                    <h3>Gainage</h3>
                    <p>
                        En appui sur les avant-bras ou les mains et sur les pieds ou les genoux, on maintient le corps
                        aligné en contractant la sangle abdominale, sans retenir sa respiration.
                    </p>
                    <p><strong>Muscles ciblés :</strong> muscles profonds de l'abdomen, lombaires, épaules et hanches.</p>
                </article>
